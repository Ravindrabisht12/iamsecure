export const RULES = { js: JS, php: PHP, py: PY };

export function langOf(file) {
  if (/\.php$/.test(file)) return 'php';
  if (/\.py$/.test(file)) return 'py';
  if (/\.([cm]?[jt]sx?|vue|svelte|astro)$/.test(file)) return 'js';
  return null;
}
