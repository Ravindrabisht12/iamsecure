// Code rules. Each rule is a line-level sink pattern plus how much it matters:
//   when: 'always'  → report any match
//         'dynamic' → only when the argument is built at runtime (template literal, concatenation, variable)
//         'tainted' → only when user input flows in (req.query, searchParams, $_GET, request.args, …)
//   sev / taintedSev: severity score without / with proven user input.
//   category: vulnerability class (see risk/score.js) — decides how much browser-only code is discounted.
//   requires: file must match this before the rule is tried.  context: override where the issue "runs".

